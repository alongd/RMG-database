#!/usr/bin/env python
"""Render state-resolved PlasmaArgon owners from sourced cascade yields."""
import argparse
import hashlib
import math
import re
from pathlib import Path
import sys

import yaml

ROOT = Path(__file__).resolve().parents[1]
YIELDS = ROOT / 'input/eedf/argon_cascade_yields.yaml'
REACTIONS = ROOT / 'input/kinetics/libraries/PlasmaArgon/reactions.py'
BEGIN = '# BEGIN GENERATED ARGON CASCADE REACTIONS'
END = '# END GENERATED ARGON CASCADE REACTIONS'
PRODUCTS = [
    ('Ar(1s5)', 'Ars'),
    ('Ar(1s4)', 'Ar(1s4)'),
    ('Ar(1s3)', 'Ar(1s3)'),
    ('Ar(1s2)', 'Ar(1s2)'),
]
EXPECTED_CHANNELS = list(range(6, 39))
FOUR_S_CHANNELS = list(range(45, 97)) + list(range(99, 125)) + list(range(128, 154))


def render(yields_raw):
    """Render four library owners per complete sourced cascade channel."""
    document = yaml.safe_load(yields_raw)
    if document.get('schema_version') != 1 or document.get('radiative_model') != 'E1':
        raise ValueError('unsupported cascade yield document')
    channels = document.get('channels')
    if not isinstance(channels, list):
        raise ValueError('cascade yield channels must be a list')
    selected = [row for row in channels if row.get('status') == 'complete_for_E1']
    if [row.get('id') for row in selected] not in (EXPECTED_CHANNELS, EXPECTED_CHANNELS + FOUR_S_CHANNELS):
        raise ValueError('expected complete ground or ground-plus-4s cascade channel set')
    if len(document.get('source_sha256', '')) != 64:
        raise ValueError('invalid radiative source digest')
    yield_digest = hashlib.sha256(yields_raw).hexdigest()

    lines = [BEGIN, '# Generated by scripts/gen_argon_cascade_reactions.py; do not edit.']
    for channel in selected:
        match = re.match(r'^e \+ Ar\((1S0|3P2|3P1|3P0|1P1)\) -> ', channel['process'])
        if match is None:
            raise ValueError('invalid cascade source identity')
        source = {'1S0': 'Ar', '3P2': 'Ars', '3P1': 'Ar(1s4)',
                  '3P0': 'Ar(1s3)', '1P1': 'Ar(1s2)'}[match[1]]
        yields = channel.get('product_yields')
        if (not isinstance(yields, dict) or set(yields) != {p for p, _ in PRODUCTS}
                or any(type(value) not in (int, float) or not math.isfinite(value) or value < 0
                       for value in yields.values())
                or abs(sum(yields.values()) - 1.0) > 1e-12):
            raise ValueError(f"channel {channel.get('id')}: invalid sourced product yields")
        if not channel.get('transition_ids') or not channel.get('process'):
            raise ValueError(f"channel {channel.get('id')}: missing source identity")
        for offset, (product, label) in enumerate(PRODUCTS):
            index = 1000 + channel['id'] * 4 + offset
            lines.extend([
                '',
                'entry(',
                f'    index = {index},',
                f'    label = "{source} + e- => {label} + e-",',
                '    reversible = False,',
                '    duplicate = True,',
                '    kinetics = EEDFChannel(',
                f"        process = {channel['process']!r},",
                '        collision_set = "IST-Lisbon-Ar-2021",',
                f'        branch_product = {product!r},',
                f'        branch_yield = {yields[product]!r},',
                f"        yield_table_sha256 = {yield_digest!r},",
                '    ),',
                f'    shortDesc = "IST-Lisbon-Ar-2021 channel {channel["id"]}; sourced cascade branch",',
                '    longDesc = """',
                f"Sourced E1 cascade branch for channel {channel['id']}. Product fractions are generated",
                'from argon_cascade_yields.yaml. Transition A values, citations and NIST row identities',
                'are recorded in argon_radiative_data.yaml. Branch fractions partition the existing',
                'electron collision rate; photon energy is accounted for once through branch products.',
                f"Transition rows: {', '.join(channel['transition_ids'])}.",
                '""",',
                ')',
            ])
    lines.extend(['', END, ''])
    return '\n'.join(lines)


def replace_region(original, generated):
    """Replace only one marked generated region; refuse missing/duplicate markers."""
    if original.count(BEGIN) != 1 or original.count(END) != 1:
        raise ValueError('expected exactly one generated-region marker pair')
    start = original.index(BEGIN)
    end = original.index(END) + len(END)
    if end < start:
        raise ValueError('generated-region markers are out of order')
    return original[:start] + generated.rstrip('\n') + original[end:]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--yields', type=Path, default=YIELDS)
    parser.add_argument('--reactions', type=Path, default=REACTIONS)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = replace_region(args.reactions.read_text(), render(args.yields.read_bytes()))
    if args.check:
        if args.reactions.read_text() != text:
            parser.error('generated cascade reactions differ; rerun scripts/gen_argon_cascade_reactions.py')
    else:
        args.reactions.write_text(text)
    print(f'argon cascade reactions: {text.count("branch_product = ")} sourced branch owners')
    return 0


if __name__ == '__main__':
    sys.exit(main())
