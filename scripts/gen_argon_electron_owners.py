#!/usr/bin/env python
"""Collect irreversible ine/sup owners for resolved argon electron collisions."""
import argparse
from pathlib import Path
import re

import yaml

ROOT = Path(__file__).resolve().parents[1]
CHANNEL_MAP = ROOT / 'input/eedf/argon_channel_map.yaml'
REACTIONS = ROOT / 'input/kinetics/libraries/PlasmaArgon/reactions.py'
BEGIN = '# BEGIN GENERATED ARGON DIRECTIONAL REACTIONS'
END = '# END GENERATED ARGON DIRECTIONAL REACTIONS'
GROUND_IDS = (2, 3, 4, 5)
MIXING_IDS = (44, 97, 98, 125, 126, 127)
ION_IDS = (154, 155, 156, 157)
LABELS = {'1S0': 'Ar', '3P2': 'Ars', '3P1': 'Ar(1s4)', '3P0': 'Ar(1s3)', '1P1': 'Ar(1s2)'}


def reversible_process(process):
    return process.replace(' -> ', ' <-> ')


def render(document):
    """Render separate irreversible entries; sup always uses the same physical column."""
    rows = {c['id']: c for c in document['channels']}
    lines = [BEGIN, '# Generated by scripts/gen_argon_electron_owners.py; do not edit.']
    for ident in GROUND_IDS + MIXING_IDS + ION_IDS:
        row = rows[ident]
        process = row['loki_process']
        source_match = re.match(r'^e \+ Ar\((1S0|3P2|3P1|3P0|1P1)\) ', process)
        if source_match is None:
            raise ValueError('unknown directional source state')
        source = LABELS[source_match[1]]
        if ident in ION_IDS:
            if row['threshold_eV'] != 4.2 or not process.endswith(', Ionization'):
                raise ValueError('stepwise ionization must retain the frozen 4.2 eV convention')
            target, sides, kind = 'Arp', ('ine',), 'stepwise ionization'
            note = ('TRINITI 4.2 eV threshold retained for every 4s level. '
                    'Consumes one electron and produces two: net electron +1 and total charge conserved.')
        else:
            process = reversible_process(process)
            match = re.search(r' <-> e \+ Ar\((3P2|3P1|3P0|1P1)\), Excitation$', process)
            if match is None:
                raise ValueError('invalid reversible argon collision')
            target = LABELS[match[1]]
            sides = ('sup',) if ident in GROUND_IDS else ('ine', 'sup')
            kind = 'ground inverse' if ident in GROUND_IDS else '4s mixing'
            note = ('Rate supplied by the named ine/sup EEDF column of the versioned reversible '
                    'collision realization. No thermal equilibrium reverse rate is used.')
        for side in sides:
            lhs, rhs = (target, source) if side == 'sup' else (source, target)
            equation = f'{lhs} + e- => {rhs} + e-' + (' + e-' if ident in ION_IDS else '')
            index = 2000 + 2 * ident + (side == 'sup')
            lines.extend(['', 'entry(', f'    index = {index},', f'    label = {equation!r},',
                          '    reversible = False,', '    duplicate = True,',
                          '    kinetics = EEDFChannel(', f'        process = {process!r},',
                          '        collision_set = "IST-Lisbon-Ar-2021",', f'        side = {side!r},',
                          '    ),', f'    shortDesc = "channel {ident}; {kind}; {side}",',
                          f'    longDesc = {note!r},', ')'])
    return '\n'.join(lines + ['', END, ''])


def update(original, document):
    """Keep existing ground indices and replace only the directional owner region."""
    text = original
    rows = {c['id']: c for c in document['channels']}
    for ident in GROUND_IDS:
        new = reversible_process(rows[ident]['loki_process'])
        old = new.replace(' <-> ', ' -> ')
        if text.count(repr(old)) == 1:
            text = text.replace(repr(old), repr(new), 1)
        elif text.count(repr(new)) not in (1, 2):
            raise ValueError('ground owner process missing or duplicated')
    generated = render(document).rstrip('\n')
    if BEGIN not in text and END not in text:
        return text.rstrip() + '\n\n' + generated + '\n'
    if text.count(BEGIN) != 1 or text.count(END) != 1 or text.index(END) < text.index(BEGIN):
        raise ValueError('invalid directional generated region')
    return text[:text.index(BEGIN)] + generated + text[text.index(END) + len(END):]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--channel-map', type=Path, default=CHANNEL_MAP)
    parser.add_argument('--reactions', type=Path, default=REACTIONS)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = update(args.reactions.read_text(), yaml.safe_load(args.channel_map.read_bytes()))
    if args.check:
        if text != args.reactions.read_text():
            parser.error('directional owners differ; rerun scripts/gen_argon_electron_owners.py')
    else:
        args.reactions.write_text(text)
    print('argon directional owners: 4 ground sup, 12 mixing directions, 4 stepwise ionizations')


if __name__ == '__main__':
    main()
