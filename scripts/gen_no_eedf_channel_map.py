"""NO metadata derivation for gen_eedf_channel_map.py --gas no.

Reads Hayashi's local ZIP without extracting or retaining cross-section payloads.
This path does not assemble LoKI-B inputs or implement runtime energy transfer.
"""

import collections
import hashlib
import io
import math
from pathlib import Path
import re
import zipfile

import yaml

import gen_eedf_channel_map as gen


HEADER = ('# Frozen NO electron-collision source inventory. GENERATED by scripts/gen_eedf_channel_map.py --gas no.\n'
          '# Local Hayashi source only; no LXCat payloads. Regenerate with the same arguments and --check.\n')
SCHEMA = 'eedf-channel-map/2'
FLUX_GROUP = 'NO_lumped_vibrational_heating'
ASSEMBLED_FILE = 'NO_assembled.txt'
SET = 'no-hayashi-v1'
NO_GROUND_STATE_SOURCE = (
    'Wong et al., ExoMol line list XXI: Nitric Oxide (NO), '
    'MNRAS 470, 882 (2017), DOI: 10.1093/mnras/stx1211; '
    'X $^2\\Pi$ term, (2S+1) × 2 = 4 for a non-Σ term (two ±Λ components).')
HEADER = ('# Frozen NO electron-collision channel map (D-232). GENERATED by scripts/gen_eedf_channel_map.py --gas no.\n'
          '# Source blocks, solver labels, assembled-file hashes and owner bindings are regenerated from the local store.\n')
MEMBER = 'Cross section.txt'
LIBRARIES = ('PlasmaNitricOxide',)
V_REASON = ('Hayashi V1-V5 are lumped vibrational energy-loss groups, not state-to-state NO(v) data. '
            'Report-10 limitation: NO has no vibrational populations. The lost electron energy goes '
            'to gas heating, assuming V-T relaxation is fast relative to the residence time.')
E_REASON = ('Hayashi e1/e2 have no sourced NO electronic species in the database inventory; '
            'ownerless electron energy loss, with no tracked electronic population or assigned radiative yield.')
ATTACHMENT_RULING = ('PM-approved dissociative attachment: e + NO -> N + O-. The source label says NO- '
                    'and its comment only gives an onset; it does not identify the physical products. '
                    'Use N + O- by the approved interpretation, not a molecular NO- owner.')


def digest(data):
    return hashlib.sha256(data).hexdigest()


def source_channels(data):
    """Derive metadata, never cross-section values, from all and only NO blocks."""
    text = data.decode('utf-8').replace('\r\n', '\n').replace('\r', '\n')
    channels = []
    for ordinal, line, raw in gen.blocks(text):
        lines = raw.splitlines()
        if lines[1] != 'NO' and not lines[1].startswith('NO -> '):
            continue
        if sum(bool(gen.DASHES.fullmatch(value)) for value in lines) != 2:
            raise ValueError(f'NO block {ordinal}: incomplete source block')
        fields = {}
        for value in lines:
            if value.startswith(('PROCESS:', 'PARAM.:', 'COMMENT:')):
                key, value = value.split(':', 1)
                if key in fields:
                    raise ValueError(f'NO block {ordinal}: duplicate {key}')
                fields[key] = value.strip()
        if not {'PROCESS', 'PARAM.'} <= fields.keys():
            raise ValueError(f'NO block {ordinal}: missing PROCESS or PARAM.')
        process, param = fields['PROCESS'], fields['PARAM.']
        c = dict(id=len(channels) + 1, source_process=process,
                 source=dict(block=ordinal, line=line, block_sha256=digest(raw.encode())),
                 kind=lines[0], threshold_eV=None, superelastic_in_set=False)
        if lines[0] == 'EFFECTIVE' and lines[1] == 'NO':
            match = re.fullmatch(r'm/M = (' + gen.NUMBER + r'), complete set', param)
            if not match or not math.isfinite(float(match[1])) or float(match[1]) <= 0:
                raise ValueError('NO EFFECTIVE: invalid mass ratio parameter')
            c.update(family='effective momentum transfer', mass_ratio=float(match[1]))
        else:
            match = re.fullmatch(r'E = (' + gen.NUMBER + r') eV, complete set', param)
            if not match or not math.isfinite(float(match[1])) or float(match[1]) < 0:
                raise ValueError(f'{process}: invalid energy-loss parameter')
            c['energy_loss_eV'] = float(match[1])
            if lines[0] == 'ATTACHMENT' and lines[1] == 'NO -> NO^-':
                onset = re.fullmatch(r'Threshold (' + gen.NUMBER + r')eV\.', fields.get('COMMENT', ''))
                if not onset or not math.isfinite(float(onset[1])) or float(onset[1]) < 0:
                    raise ValueError('NO attachment: missing source-comment onset')
                c.update(family='dissociative attachment', source_comment=fields['COMMENT'],
                         comment_onset_eV=float(onset[1]), physical_products=['N', 'O-'],
                         product_interpretation=ATTACHMENT_RULING)
            elif lines[0] == 'IONIZATION' and lines[1] == 'NO -> NO^+':
                c.update(family='ionization', threshold_eV=c['energy_loss_eV'])
            elif lines[0] == 'EXCITATION':
                state = re.fullmatch(r'NO -> NO\((V[1-5]|e[12])\)\((' + gen.NUMBER + r')eV\)', lines[1])
                if not state or float(state[2]) != c['energy_loss_eV']:
                    raise ValueError(f'{process}: unsupported state or threshold disagrees with label')
                c.update(family='lumped vibrational' if state[1].startswith('V') else 'electronic excitation',
                         group=state[1], threshold_eV=c['energy_loss_eV'])
            else:
                raise ValueError(f'{process}: unsupported NO process')
        kind = {'EFFECTIVE': 'Effective', 'ATTACHMENT': 'Attachment',
                'EXCITATION': 'Excitation', 'IONIZATION': 'Ionization'}[c['kind']]
        target = lines[1].split(' -> ')[-1].replace('^', '')
        electrons = {'EFFECTIVE': 'E + ', 'ATTACHMENT': '',
                     'EXCITATION': 'E + ', 'IONIZATION': 'E + E + '}[c['kind']]
        if process != f'E + NO -> {electrons}{target}, {kind}':
            raise ValueError(f'{process}: PROCESS disagrees with the source target/product')
        channels.append(c)
    groups = [c.get('group') for c in channels if 'group' in c]
    families = collections.Counter(c['family'] for c in channels)
    if (len(channels) != 10 or sorted(groups) != ['V1', 'V2', 'V3', 'V4', 'V5', 'e1', 'e2']
            or families != {'effective momentum transfer': 1, 'dissociative attachment': 1,
                            'ionization': 1, 'lumped vibrational': 5, 'electronic excitation': 2}
            or len({c['source_process'] for c in channels}) != len(channels)):
        raise ValueError('Hayashi must contain exactly the ten unique NO processes, including V1-V5 and e1/e2')
    attribution = {}
    for key in ('DATABASE', 'PERMLINK'):
        values = [x.split(':', 1)[1].strip() for x in text.splitlines() if x.startswith(key + ':')]
        if len(values) != 1:
            raise ValueError(f'expected one source {key}')
        attribution[key.lower()] = values[0]
    return channels, attribution


def policy(channel):
    family = channel['family']
    if family == 'lumped vibrational':
        return 'B', None, 'gas_heating', V_REASON
    if family == 'electronic excitation':
        return 'B', None, 'ownerless_electronic_energy', E_REASON
    if family == 'effective momentum transfer':
        return ('B', None, 'effective_momentum_transfer',
                'Hayashi supplies EFFECTIVE total momentum transfer, not a pure elastic cross section; '
                'its mass ratio is not an excitation threshold. No species transition or extra inelastic '
                'energy-loss term is assigned by this map.')
    if family == 'dissociative attachment':
        return ('A', 'NO + e- => N + O-', 'chemical_products',
                'Dissociative attachment needs an explicit owner reaction; N and O- species exist in '
                'PlasmaNitricOxide. '
                'PARAM E is the attachment energy-loss parameter, not a threshold; '
                'the source-comment onset is recorded separately.')
    return ('A', 'NO + e- => NOp + e- + e-', 'ionization',
            'NO+ is PlasmaNitricOxide/NOp. Species presence is not reaction ownership.')


def _validate_store(archive, assembled):
    """Require every file in the named local store to match deterministic assembly."""
    import assemble_no_loki_collisions as assembly

    expected = assembly.build(archive)
    folder = Path(assembled)
    if not folder.is_dir():
        raise ValueError(f'--assembled {folder}: not a directory')
    names = sorted(path.name for path in folder.iterdir() if path.is_file())
    if names != sorted(expected):
        raise ValueError(f'--assembled {folder}: file inventory differs: {names!r}')
    for name, data in expected.items():
        if (folder / name).read_bytes() != data:
            raise ValueError(f'--assembled {folder}: {name} differs from deterministic assembly')
    return folder, expected


def generate(overlay, archive, assembled, database):
    """Generate converter `/2` NO metadata from the assembled store and Hayashi source."""
    overlay, references, problems = gen.load_overlay_document(overlay)
    if problems:
        return None, problems, '', []
    archive_data = Path(archive).read_bytes()
    with zipfile.ZipFile(io.BytesIO(archive_data)) as source:
        if source.namelist().count(MEMBER) != 1:
            raise ValueError(f'archive must contain exactly one {MEMBER}')
        source_data = source.read(MEMBER)
    source_rows, attribution = source_channels(source_data)
    folder, assembled_files = _validate_store(archive, assembled)
    collision_bytes = assembled_files[ASSEMBLED_FILE]
    collision_digest = digest(collision_bytes)
    try:
        from rmgpy.tools.eedf.channels import _classic_sections
        sections = _classic_sections(str(folder / ASSEMBLED_FILE), collision_digest)
    except Exception as exc:
        raise ValueError(f'assembled NO file is not accepted by the target converter parser: {exc}') from exc
    if len(sections) != len(source_rows):
        raise ValueError(f'assembled NO collision count {len(sections)} differs from source inventory {len(source_rows)}')
    labels = [section['description'] for section in sections]
    if len(set(labels)) != len(labels):
        raise ValueError('assembled NO file contains duplicate solver identities')
    if set(overlay) != set(labels):
        raise ValueError(f'overlay coverage differs: missing {sorted(set(labels) - set(overlay))}; '
                         f'extra {sorted(set(overlay) - set(labels))}')

    reactions, species, library_problems = gen.load_library(database, LIBRARIES[0])
    if library_problems:
        raise ValueError('; '.join(library_problems))
    from rmgpy.molecule import Molecule
    expected_species = {'NO', 'N', 'O-', 'NOp', 'e-'}
    if set(references) != expected_species:
        raise ValueError('overlay species must be exactly NO, N, O-, NOp and e-')
    owners = {}
    for name, record in references.items():
        reference = Molecule().from_adjacency_list(record)
        if name not in species:
            raise ValueError(f'owner species {name} absent from {LIBRARIES[0]}')
        problem = gen.identity_problem(species[name], reference)
        if problem:
            raise ValueError(f'{LIBRARIES[0]}/{name}: {problem}')
        owners[name] = dict(libraries=[LIBRARIES[0]], record=record)

    map_channels = []
    for source_channel, section in zip(source_rows, sections):
        label = section['description']
        classification, reaction, sink, reason = policy(source_channel)
        entry = overlay[label]
        if entry != {'class': classification, 'reaction': reaction}:
            raise ValueError(f'{label}: overlay disagrees with NO policy')
        row = {
            'id': source_channel['id'], 'loki_process': label, 'lxcat_file': ASSEMBLED_FILE,
            'source_process': source_channel['source_process'], 'source': source_channel['source'],
            'kind': source_channel['kind'], 'threshold_eV': section['threshold_eV'],
            'class': classification, 'reason': reason, 'energy_sink': sink,
            'energy_loss_eV': source_channel.get('energy_loss_eV'),
            'comment_onset_eV': source_channel.get('comment_onset_eV'),
        }
        if source_channel.get('group'):
            row['group'] = source_channel['group']
        if source_channel['family'] == 'lumped vibrational':
            row['flux_group'] = FLUX_GROUP
        if classification == 'A':
            parsed = gen.parse_reaction(reaction)
            lhs, arrow, rhs = parsed
            if arrow != '=>' or len(lhs) != 2 or len(rhs) not in (2, 3):
                raise ValueError(f'{label}: invalid expected owner reaction')
            matches = [index for index, loaded in reactions.items()
                       if loaded.reactants == tuple(sorted(lhs)) and loaded.products == tuple(sorted(rhs))
                       and not loaded.reversible and loaded.has_eedf_marker
                       and loaded.eedf_process == label and loaded.eedf_collision_set == SET]
            if len(matches) != 1:
                raise ValueError(f'{label}: expected one exact {LIBRARIES[0]} EEDF owner, found {matches}')
            index = matches[0]
            row['rmg'] = {'library': LIBRARIES[0], 'index': index, 'reaction': reaction,
                          'status': 'present', 'checked_libraries': [LIBRARIES[0]], 'matches': [index],
                          'species': {name: [LIBRARIES[0]] for name in sorted(set(lhs + rhs))}}
            row['reason'] += f' Owner reaction {reaction} is present in {LIBRARIES[0]}[{index}].'
        else:
            row['rmg'] = None
        map_channels.append(row)

    counts = {key: sum(row['class'] == key for row in map_channels) for key in 'ABCD'}
    v_ids = [row['id'] for row in map_channels if row.get('group') in {'V1', 'V2', 'V3', 'V4', 'V5'}]
    doc = {
        'schema': SCHEMA, 'set': SET, 'data_policy': gen.DATA_POLICY,
        'loki_files': {ASSEMBLED_FILE: collision_digest},
        'sources': {Path(archive).name: {'database': attribution['database'],
                    'permlink': attribution['permlink'], 'file': Path(archive).name,
                    'sha256': digest(archive_data), 'member': MEMBER,
                    'member_sha256': digest(source_data),
                    'n_blocks': len(list(gen.blocks(source_data.decode('utf-8')))),
                    'blocks_used': len(map_channels)}},
        'species': owners,
        'states': {'NO(X)': {'paschen': 'ground', 'g': 4, 'excitation_eV': 0.0,
                             'rmg_species': 'NO', 'source': NO_GROUND_STATE_SOURCE}},
        'declared_conventions': [
            {'name': 'LUMPED_VIBRATIONAL_GAS_HEATING', 'statement': V_REASON, 'applies_to': v_ids},
            {'name': 'DISSOCIATIVE_ATTACHMENT_INTERPRETATION', 'statement': ATTACHMENT_RULING,
             'applies_to': [row['id'] for row in map_channels if row['kind'] == 'ATTACHMENT']}],
        'class_counts': counts, 'class_a_gaps': {}, 'channels': map_channels,
    }
    text = HEADER + yaml.dump(doc, Dumper=gen._Dumper, sort_keys=False, width=110, allow_unicode=False)
    summary = f'NO channels {len(map_channels)}; classes A={counts["A"]} B={counts["B"]} C={counts["C"]} D={counts["D"]}'
    return text, [], summary, labels
